Invoke-LicenseCase 'unknown output rejected' {
    [void](Get-Vkd3dShaderGeneratedLicense `
        -RelativePath 'include/unknown.h' -Bytes $flex `
        -InputRelativePaths @('include/unknown.in'))
} $false

Invoke-LicenseCase 'CRLF output rejected' {
    [void](Get-Vkd3dShaderGeneratedLicense `
        -RelativePath 'libs/vkd3d-shader/hlsl.yy.c' `
        -Bytes $utf8.GetBytes("A lexical scanner generated by flex`r`n") `
        -InputRelativePaths @('libs/vkd3d-shader/hlsl.l'))
} $false

Invoke-LicenseCase 'UTF-8 BOM output rejected' {
    [byte[]]$bom = 0xef, 0xbb, 0xbf
    [void](Get-Vkd3dShaderGeneratedLicense `
        -RelativePath 'libs/vkd3d-shader/hlsl.yy.c' `
        -Bytes ($bom + $flex) `
        -InputRelativePaths @('libs/vkd3d-shader/hlsl.l'))
} $false

foreach ($badPath in @(
    'C:/private/hlsl.yy.c',
    'C:private/hlsl.yy.c',
    'libs/./hlsl.yy.c',
    'libs//hlsl.yy.c',
    'libs\hlsl.yy.c',
    ('libs/' + ('x' * 1024))
)) {
    Invoke-LicenseCase "unsafe output path rejected: $badPath" {
        [void](Get-Vkd3dShaderGeneratedLicense `
            -RelativePath $badPath -Bytes $flex `
            -InputRelativePaths @('libs/vkd3d-shader/hlsl.l'))
    } $false
}

Invoke-LicenseCase 'unsafe generated input path rejected' {
    [void](Get-Vkd3dShaderGeneratedLicense `
        -RelativePath 'libs/vkd3d-shader/hlsl.yy.c' `
        -Bytes $flex -InputRelativePaths @('C:/private/hlsl.l'))
} $false

Write-Host "vkd3d-shader generated-license tests: $passed passed, $failed failed"
if ($failed -ne 0) { exit 1 }
