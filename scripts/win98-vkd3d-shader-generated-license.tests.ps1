    $bytes = $utf8.GetBytes(
        'Autogenerated by WIDL 11.0-rc1 from include/vkd3d_d3dcommon.idl' + "`n"
    )
    [void](Get-TestGeneratedLicense `
        'include/vkd3d_d3dcommon.h' $bytes)
} $true

Invoke-LicenseCase 'WIDL exact secondary input disposition' {
    $bytes = $utf8.GetBytes(
        'Autogenerated by WIDL 11.0-rc1 from include/vkd3d_d3dx9shader.idl' + "`n"
    )
    [void](Get-TestGeneratedLicense `
        'include/vkd3d_d3dx9shader.h' $bytes)
} $true

