[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'
. (Join-Path $PSScriptRoot 'vkd3d-shader-source-root.ps1')
. (Join-Path $PSScriptRoot 'vkd3d-shader-generated-license.ps1')

$utf8 = [Text.UTF8Encoding]::new($false)
$passed = 0
$failed = 0
$inputsByOutput = @{
    'libs/vkd3d-shader/hlsl.yy.c' = @('libs/vkd3d-shader/hlsl.l')
    'libs/vkd3d-shader/hlsl.tab.c' = @('libs/vkd3d-shader/hlsl.y')
    'libs/vkd3d-shader/hlsl.tab.h' = @('libs/vkd3d-shader/hlsl.y')
    'libs/vkd3d-shader/preproc.yy.c' = @('libs/vkd3d-shader/preproc.l')
    'libs/vkd3d-shader/preproc.tab.c' = @('libs/vkd3d-shader/preproc.y')
    'libs/vkd3d-shader/preproc.tab.h' = @('libs/vkd3d-shader/preproc.y')
    'include/vkd3d_d3dcommon.h' = @(
        'include/vkd3d_d3dcommon.idl',
        'include/vkd3d_unknown.idl'
    )
    'include/vkd3d_d3dx9shader.h' = @(
        'include/vkd3d_d3dx9shader.idl',
        'include/vkd3d_d3d9types.h'
    )
    'include/private/spirv_grammar.h' = @(
        'libs/vkd3d-shader/make_spirv',
        'include/private/spirv.core.grammar.json'
    )
    'include/config.h' = @('configure.ac')
    'include/private/vkd3d_version.h' = @('Makefile.am')
}

function Invoke-LicenseCase {
    param([string]$Name, [scriptblock]$Body, [bool]$ShouldPass)

    try {
        & $Body
        if (-not $ShouldPass) { throw 'Expected rejection.' }
        $script:passed++
    }
    catch {
        if ($ShouldPass) {
            $script:failed++
            Write-Host "FAIL: $Name - $($_.Exception.Message)"
        }
        else { $script:passed++ }
    }
}

function Get-TestGeneratedLicense {
    param([string]$RelativePath, [byte[]]$Bytes)

    return Get-Vkd3dShaderGeneratedLicense -RelativePath $RelativePath `
        -Bytes $Bytes -InputRelativePaths @($inputsByOutput[$RelativePath])
}

$bison = $utf8.GetBytes(@'
GNU General Public License as published by
either version 3 of the License, or
As a special exception, you may create a larger work
'@.Replace("`r`n", "`n") + "`n")
$flex = $utf8.GetBytes(
    "A lexical scanner generated by flex`nterms of the GNU Lesser General Public`n"
)

foreach ($path in @(
    'libs/vkd3d-shader/hlsl.tab.c',
    'libs/vkd3d-shader/hlsl.tab.h',
    'libs/vkd3d-shader/preproc.tab.c',
    'libs/vkd3d-shader/preproc.tab.h'
)) {
    Invoke-LicenseCase "Bison disposition $path" {
        $result = Get-TestGeneratedLicense $path $bison
        if ($result.license_expression -cne
            'LGPL-2.1-or-later AND (GPL-3.0-or-later WITH Bison-exception-2.2)') {
            throw 'Bison expression changed.'
        }
        if ($result.provenance -cne
            'bison-3.8.2-skeleton-exception-and-exact-lgpl-grammar-input') {
            throw 'Bison provenance changed.'
        }
    } $true
}

Invoke-LicenseCase 'Bison header uses exact grammar provenance' {
    $header = $utf8.GetBytes(
        "GNU General Public License as published by`n" +
        "either version 3 of the License, or`n" +
        "As a special exception, you may create a larger work`n"
    )
    [void](Get-TestGeneratedLicense `
        'libs/vkd3d-shader/hlsl.tab.h' $header)
} $true

Invoke-LicenseCase 'Bison GPL version drift rejected' {
    $wrongVersion = $utf8.GetBytes(
        "GNU General Public License as published by`n" +
        "either version 2 of the License, or`n" +
        "As a special exception, you may create a larger work`n"
    )
    [void](Get-Vkd3dShaderGeneratedLicense `
        -RelativePath 'libs/vkd3d-shader/hlsl.tab.h' `
        -Bytes $wrongVersion `
        -InputRelativePaths @('libs/vkd3d-shader/hlsl.y'))
} $false

Invoke-LicenseCase 'Bison C rejects wrong grammar binding' {
    [void](Get-Vkd3dShaderGeneratedLicense `
        -RelativePath 'libs/vkd3d-shader/hlsl.tab.c' `
        -Bytes $bison `
        -InputRelativePaths @('libs/vkd3d-shader/preproc.y'))
} $false

Invoke-LicenseCase 'Bison C rejects case-drifted grammar binding' {
    [void](Get-Vkd3dShaderGeneratedLicense `
        -RelativePath 'libs/vkd3d-shader/hlsl.tab.c' `
        -Bytes $bison `
        -InputRelativePaths @('libs/vkd3d-shader/HLSL.y'))
} $false

Invoke-LicenseCase 'Bison C rejects missing grammar binding' {
    [void](Get-Vkd3dShaderGeneratedLicense `
        -RelativePath 'libs/vkd3d-shader/hlsl.tab.c' `
        -Bytes $bison `
        -InputRelativePaths @())
} $false

foreach ($path in @(
    'libs/vkd3d-shader/hlsl.yy.c',
    'libs/vkd3d-shader/preproc.yy.c'
)) {
    Invoke-LicenseCase "Flex disposition $path" {
        $result = Get-TestGeneratedLicense $path $flex
        if ($result.license_expression -cne 'LGPL-2.1-or-later') {
            throw 'Flex expression changed.'
        }
    } $true
}

