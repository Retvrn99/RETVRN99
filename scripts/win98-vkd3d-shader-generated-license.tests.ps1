    $bytes = $utf8.GetBytes(
        'Autogenerated by WIDL 11.0-rc1 from include/other.idl' + "`n"
    )
    [void](Get-Vkd3dShaderGeneratedLicense `
        -RelativePath 'include/vkd3d_d3dcommon.h' `
