    $bytes = $utf8.GetBytes(
        "The original source is covered by the following license:`n" +
        "Permission is hereby granted, free of charge`n"
    )
    [void](Get-TestGeneratedLicense `
        'include/private/spirv_grammar.h' $bytes)
} $true

